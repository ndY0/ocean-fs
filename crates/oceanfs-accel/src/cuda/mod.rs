#[inline]
fn gf_mul_portable(a: u8, b: u8) -> u8 {
    if a == 0 || b == 0 {
        return 0;
    }
    let sum = GF_LOG[a as usize] as u16 + GF_LOG[b as usize] as u16;
    GF_EXP[(sum % 255) as usize]
}

#[inline]
fn gf_inv_portable(a: u8) -> u8 {
    if a == 0 {
        return 0;
    }
    GF_EXP[(255 - GF_LOG[a as usize] as usize) % 255]
}

