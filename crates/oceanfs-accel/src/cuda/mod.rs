#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn cuda_backend_probe() {
        let config = GpuConfig::default();
        let backend = CudaBackend::new(config);
        if let Some(ref b) = backend {
            assert!(b.is_available());
        }
    }

    #[test]
    fn gpu_config_stored() {
        let config = GpuConfig { device_id: 0, ..Default::default() };
        if let Some(backend) = CudaBackend::new(config) {
            assert_eq!(backend.config().device_id, 0);
        }
    }

    #[test]
    fn should_use_gpu_respects_threshold() {
        let config = GpuConfig { min_segment_size: 100, ..Default::default() };
        if let Some(backend) = CudaBackend::new(config) {
            assert!(!backend.should_use_gpu(50));
            assert!(backend.should_use_gpu(200));
        }
    }

    #[test]
    fn mark_unavailable() {
        let config = GpuConfig::default();
        if let Some(backend) = CudaBackend::new(config) {
            assert!(backend.is_available());
            backend.mark_unavailable();
            assert!(!backend.is_available());
        }
    }

    #[test]
    fn gf_mul_split_table_correct() {
        for coeff in 1..=255u8 {
            let table = GfMulTable::new(coeff);
            for b in 0..=255u8 {
                let lo_idx = (b & 0x0F) as usize;
                let hi_idx = (b >> 4) as usize;
                let reconstructed = table.lo[lo_idx] ^ table.hi[hi_idx];
                assert_eq!(reconstructed, gf_mul_portable(coeff, b));
            }
        }
    }

    #[test]
    fn gpu_tables_build() {
        let tables = GpuEncodeTables::new(4, 2);
        assert_eq!(tables.k, 4);
        assert_eq!(tables.m, 2);
        assert_eq!(tables.data.len(), 256);
    }

    #[test]
    fn gf_mul_identity() {
        for a in 1..=255u8 {
            assert_eq!(gf_mul_portable(a, 1), a);
        }
    }

    /// Full GPU encode + CPU decode roundtrip test.
    /// Runs only when a CUDA GPU is available.
    #[test]
    fn encode_gpu_decode_cpu_roundtrip() {
        let config = GpuConfig { min_segment_size: 0, ..Default::default() };
        let backend = match CudaBackend::new(config) {
            Some(b) => b,
            None => {
                eprintln!("SKIP: no CUDA device");
                return;
            }
        };

        let data: Vec<Vec<u8>> = (0..4).map(|i| vec![i; 256]).collect();
        let shard_refs: Vec<&[u8]> = data.iter().map(|v| v.as_slice()).collect();

        let parity = backend.encode(&shard_refs, 2).unwrap();
        assert_eq!(parity.len(), 2);
        assert_eq!(parity[0].len(), 256);

        // Cross-backend: decode via CPU
        let available: Vec<Option<&[u8]>> = vec![
            None,
            Some(&data[1]),
            Some(&data[2]),
            Some(&data[3]),
            Some(&parity[0]),
            Some(&parity[1]),
        ];
        let recovered = backend.decode(&available, 4, 2).unwrap();
        assert_eq!(recovered[0], data[0]);
    }
}
