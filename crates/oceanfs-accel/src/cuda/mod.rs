/// Queries total GPU memory in bytes via the CUDA driver API.
///
/// Returns 0 if the query fails.
fn query_gpu_total_memory() -> u64 {
    cudarc::driver::result::mem_get_info().map(|(_free, total)| total as u64).unwrap_or(0)
}

