// ---------------------------------------------------------------------------
// GF(2^8) split-table construction (same algorithm as NEON path)
// ---------------------------------------------------------------------------

struct GfMulTable {
    lo: [u8; 16],
    hi: [u8; 16],
}

impl GfMulTable {
    fn new(coeff: u8) -> Self {
        let mut lo = [0u8; 16];
        let mut hi = [0u8; 16];
        for i in 0..16u8 {
            lo[i as usize] = gf_mul_portable(coeff, i);
            hi[i as usize] = gf_mul_portable(coeff, i.wrapping_mul(16));
        }
        Self { lo, hi }
    }
}

struct GpuEncodeTables {
    data: Vec<u8>,
    #[allow(dead_code)]
    k: u8,
    #[allow(dead_code)]
    m: u8,
}

impl GpuEncodeTables {
    fn new(k: u8, m: u8) -> Self {
        let ki = k as usize;
        let mi = m as usize;
        let num_coeffs = ki * mi;
        let total = 2 * 16 * num_coeffs;
        let mut data = vec![0u8; total];

        for row in 0..mi {
            for col in 0..ki {
                let x = (col + 1) as u8;
                let y = (ki + row + 1) as u8;
                let coeff = gf_inv_portable(x ^ y);
                let table = GfMulTable::new(coeff);
                let base = row * ki * 16 + col * 16;
                data[base..base + 16].copy_from_slice(&table.lo);
                data[num_coeffs * 16 + base..num_coeffs * 16 + base + 16]
                    .copy_from_slice(&table.hi);
            }
        }
        Self { data, k, m }
    }
}

