//! CUDA-accelerated erasure coding backend.
//!
//! Offloads batch GF(2^8) matrix multiplication to the GPU.
//! Only compiled when the `cuda` feature is enabled.
//!
//! ## Architecture
//!
//! ```text
//! CudaBackend::encode(data_shards, m):
//!   1. Build split-tables for the encoding matrix (32 bytes per coefficient)
//!   2. Upload tables + data to GPU global memory
//!   3. Launch gf256_encode kernel: one thread per byte position
//!   4. Download parity shards from GPU
//!   5. Free device memory
//!
//! Kernel: gf256_encode
//!   Grid:  ceil(num_bytes / 256)
//!   Block: 256 threads
//!   Each thread: computes one byte of each parity shard using
//!   split-table GF(2^8) lookup (same algorithm as NEON path).
//! ```
//!
//! ## Safety
//!
//! CUDA kernel launches use `unsafe` through `cudarc`. Each `unsafe` block
//! is preceded by a `// SAFETY:` comment. `cudarc` provides safe device
//! memory management; unsafe is limited to kernel argument construction.

#[cfg(not(no_nvcomp))]
