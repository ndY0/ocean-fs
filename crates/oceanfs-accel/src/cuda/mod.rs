/// A CUDA-accelerated EC backend.
///
/// Implements `Encoder` using GPU kernel launches for batched stripe
/// operations. Decode delegates to the CPU Cauchy RS (less frequent path).
pub struct CudaBackend {
    /// CUDA device handle.
    device: Arc<CudaDevice>,
    /// GPU configuration.
    config: GpuConfig,
    /// Semaphore bounding concurrent GPU operations (per ADR-0006 §4).
    encode_semaphore: Arc<Semaphore>,
    /// Whether the GPU is currently available.
    available: AtomicBool,
    /// GPU utilization gauge (1=available, 0=unavailable).
    gpu_utilization: Gauge,
    /// GPU memory gauge (total bytes).
    gpu_memory_bytes: Gauge,
    /// Cumulative GPU encode time in microseconds.
    gpu_encode_us_total: Counter,
}

impl CudaBackend {
    /// Creates a new CUDA backend, probing for a GPU device.
    ///
    /// # Returns
    ///
    /// `None` if no CUDA device is detected or kernel compilation fails.
    pub fn new(config: GpuConfig) -> Option<Self> {
        let device = match CudaDevice::new(config.device_id) {
            Ok(dev) => {
                tracing::info!(
                    device_id = config.device_id,
                    name = dev.name().unwrap_or_default(),
                    "CUDA device initialized"
                );
                dev
            }
            Err(e) => {
                tracing::debug!(
                    device_id = config.device_id,
                    error = %e,
                    "CUDA device not available"
                );
                return None;
            }
        };

        // Load the PTX kernel module
        if let Err(e) = device.load_ptx(PTX_SRC.into(), PTX_MODULE, &[PTX_FN]) {
            tracing::error!(error = %e, "Failed to load CUDA PTX module");
            return None;
        }
        tracing::debug!("CUDA kernel {} loaded", PTX_FN);

        let encode_semaphore = Arc::new(Semaphore::new(config.max_concurrent_ops));

        // Query total GPU memory.
        let mem_bytes = query_gpu_total_memory();

        let gpu_mem = Gauge::new(
            "accel_gpu_memory_bytes".into(),
            "Total GPU memory bytes".into(),
            LabelSet::empty(),
        );
        gpu_mem.set(mem_bytes);

        let gpu_util = Gauge::new(
            "accel_gpu_utilization".into(),
            "GPU availability (1=healthy, 0=unhealthy)".into(),
            LabelSet::empty(),
        );
        gpu_util.set(1); // GPU is healthy at startup

        Some(Self {
            device,
            config,
            encode_semaphore,
            available: AtomicBool::new(true),
            gpu_utilization: gpu_util,
            gpu_memory_bytes: gpu_mem,
            gpu_encode_us_total: Counter::new(
                "accel_gpu_encode_us_total".into(),
                "Cumulative GPU encode time in microseconds".into(),
                LabelSet::empty(),
            ),
        })
    }

    /// Returns a handle to the compiled kernel function.
    fn get_kernel(&self) -> Option<CudaFunction> {
        self.device.get_func(PTX_MODULE, PTX_FN)
    }

    /// Returns `true` if the CUDA device is currently available.
    pub fn is_available(&self) -> bool {
        self.available.load(Ordering::Relaxed)
    }

    /// Marks the GPU as unavailable.
    pub fn mark_unavailable(&self) {
        self.available.store(false, Ordering::Relaxed);
        self.gpu_utilization.set(0);
        tracing::error!("CUDA device marked unavailable; entering cooldown");
    }

    /// Returns the GPU configuration.
    pub fn config(&self) -> &GpuConfig {
        &self.config
    }

    /// Determines whether a segment should use GPU acceleration.
    pub fn should_use_gpu(&self, segment_size_bytes: u64) -> bool {
        self.is_available() && segment_size_bytes >= self.config.min_segment_size
    }

    /// Registers GPU metrics with a registrar.
    pub fn register_metrics(&self, registrar: &dyn MetricRegistrar) {
        registrar.register_gauge(self.gpu_utilization.clone());
        registrar.register_gauge(self.gpu_memory_bytes.clone());
        registrar.register_counter(self.gpu_encode_us_total.clone());
    }
}

// ---------------------------------------------------------------------------
// Encoder implementation (GPU-accelerated)
// ---------------------------------------------------------------------------

impl Encoder for CudaBackend {
    fn encode(&self, data_shards: &[&[u8]], parity_count: u8) -> EcResult<Vec<Bytes>> {
        let start = Instant::now();
        let result = self.encode_impl(data_shards, parity_count);
        let elapsed_us = start.elapsed().as_micros() as u64;
        self.gpu_encode_us_total.add(elapsed_us);
        result
    }
}

impl CudaBackend {
    fn encode_impl(&self, data_shards: &[&[u8]], parity_count: u8) -> EcResult<Vec<Bytes>> {
        if !self.is_available() {
            return Err(EcError::DecodingFailed("GPU backend is unavailable (cooldown)".into()));
        }

        let m = parity_count;
        if m == 0 {
            return Ok(Vec::new());
        }
        let k = data_shards.len() as u8;
        if k == 0 {
            return Ok(Vec::new());
        }
        let shard_size = data_shards.first().map(|s| s.len()).unwrap_or(0);
        if shard_size == 0 {
            return Ok(vec![Bytes::new(); m as usize]);
        }

        // Build split-tables and flatten data
        let tables = GpuEncodeTables::new(k, m);
        let mut flat_data = Vec::with_capacity(k as usize * shard_size);
        for shard in data_shards {
            flat_data.extend_from_slice(shard);
        }

        // Verify kernel is available
        if self.get_kernel().is_none() {
            return Err(EcError::DecodingFailed("CUDA kernel not loaded".into()));
        }

        // Acquire GPU semaphore permit (per ADR-0006 §4).
        // try_acquire is non-blocking; if no permit available, return error
        // so the caller can fall back to CPU or retry.
        let _permit = self.encode_semaphore.try_acquire().map_err(|_| {
            EcError::DecodingFailed("GPU saturated — no semaphore permits available".into())
        })?;

        let num_bytes = shard_size as i32;
        let m_usize = m as usize;

        // --- GPU operations ---
        let result = (|| -> Result<Vec<Bytes>, cudarc::driver::DriverError> {
            // SAFETY: Device memory allocation on a valid, initialized CudaDevice.
            // The returned CudaSlice wraps a valid GPU pointer or returns Err.
            let mut d_data = unsafe { self.device.alloc::<u8>(flat_data.len()) }?;
            // SAFETY: Same — valid device allocation.
            let d_parity = unsafe { self.device.alloc::<u8>(m_usize * shard_size) }?;
            // SAFETY: Same — valid device allocation.
            let mut d_tables = unsafe { self.device.alloc::<u8>(tables.data.len()) }?;

            // Copy host → device
            self.device.htod_sync_copy_into(&flat_data, &mut d_data)?;
            self.device.htod_sync_copy_into(&tables.data, &mut d_tables)?;

            // Get kernel function (already verified above)
            #[allow(clippy::unwrap_used)]
            let kernel = self.get_kernel().unwrap();

            let block_dim: u32 = 256;
            let grid_dim: u32 = (num_bytes as u32).div_ceil(block_dim);

            let cfg = LaunchConfig {
                grid_dim: (grid_dim, 1, 1),
                block_dim: (block_dim, 1, 1),
                shared_mem_bytes: 0,
            };

            // SAFETY: d_data, d_parity, d_tables are valid device allocations
            // from this device. Parameter types match the kernel signature
            // (const u8*, u8*, const u8*, int, int, int).
            unsafe {
                kernel.launch(
                    cfg,
                    (
                        &d_data,   // *const u8 data
                        &d_parity, // *mut u8 parity (CudaSlice is DevicePtr)
                        &d_tables, // *const u8 tables
                        k as i32,  // int k
                        m as i32,  // int m
                        num_bytes, // int num_bytes
                    ),
                )?;
            }

            // Synchronize
            self.device.synchronize()?;

            // Copy device → host
            let mut host_parity = vec![0u8; m_usize * shard_size];
            self.device.dtoh_sync_copy_into(&d_parity, &mut host_parity)?;

            // Convert flat to Vec<Bytes> — zero-copy via Bytes::copy_from_slice
            let parity: Vec<Bytes> = (0..m_usize)
                .map(|row| {
                    let start = row * shard_size;
                    Bytes::copy_from_slice(&host_parity[start..start + shard_size])
                })
                .collect();

            Ok(parity)
        })();

        match result {
            Ok(parity) => Ok(parity),
            Err(e) => {
                tracing::error!(error = %e, "GPU encode failed");
                self.mark_unavailable();
                Err(EcError::DecodingFailed(format!("GPU encode error: {e}")))
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Decoder implementation
// ---------------------------------------------------------------------------

impl Decoder for CudaBackend {
    fn decode(
        &self,
        available_shards: &[Option<&[u8]>],
        data_count: u8,
        parity_count: u8,
    ) -> oceanfs_ec::Result<Vec<bytes::Bytes>> {
        let _ = self.is_available();
        let encoder = oceanfs_ec::CauchyEncoder::new(oceanfs_core::CodecConfig {
            data_shards: data_count,
            parity_shards: parity_count,
            ..Default::default()
        });
        encoder.decode(available_shards, data_count, parity_count)
    }
}

